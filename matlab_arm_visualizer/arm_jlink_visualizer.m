function session = arm_jlink_visualizer(varargin)
%ARM_JLINK_VISUALIZER 从 RTT Channel 1 接收关节帧并复用串口可视化器。

source = arm_jlink_byte_source( ...
    'Device', 'STM32F407IG', ...
    'Interface', 'SWD', ...
    'SpeedKHz', 4000, ...
    'Channel', 1, ...
    'AutoReleaseProbe', true);

try
    session = arm_serial_visualizer(source.description, ...
        'ByteSource', source, varargin{:});
catch exception
    source.close();
    rethrow(exception);
end
end
