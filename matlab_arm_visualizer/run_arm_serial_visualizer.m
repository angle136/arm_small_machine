%% 7轴机械臂串口一键启动（自动选择可用端口）

ENABLE_VISUALIZATION = true;
CONSOLE_DIAGNOSTICS = false;
TIMER_PERIOD_S = 0.02;
RENDER_PERIOD_S = 0.20;
BAUD_RATE = 115200;
LIVE_VISUALS = true;
DEFAULT_VIEW = 5;
JOINT_INVERSION = [1 1 1 1 1 0 0];

PORT_NAME = select_serial_port(true);
if strlength(PORT_NAME) == 0
    error('run_arm_serial_visualizer:NoPort', ...
        '没有检测到可用串口，无法启动。');
end

armSession = arm_serial_visualizer(PORT_NAME, ...
    'Visualize', ENABLE_VISUALIZATION, ...
    'ConsoleDiagnostics', CONSOLE_DIAGNOSTICS, ...
    'TimerPeriod', TIMER_PERIOD_S, ...
    'RenderPeriod', RENDER_PERIOD_S, ...
    'BaudRate', BAUD_RATE, ...
    'LiveVisuals', LIVE_VISUALS, ...
    'DefaultView', DEFAULT_VIEW, ...
    'InversionFlags', JOINT_INVERSION);
